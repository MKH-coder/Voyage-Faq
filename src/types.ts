export type FAQCategory = 
  | 'currency-budget'
  | 'transit-transport'
  | 'customs-etiquette'
  | 'connectivity-tech'
  | 'safety-emergency'
  | 'visa-passports'
  | 'baggage-packing'
  | 'health-insurance';

export interface FAQItem {
  id: string;
  orderIndex?: number;
  question: string;
  officialDirectAnswer?: string;
  answer: string;
  summary: string;
  category: FAQCategory;
  tags: string[];
  helpfulCount: number;
  unhelpfulCount: number;
  viewCount: number;
  featured: boolean;
  source: 'editorial' | 'ai-insights-engine';
  aiConfidence?: number;
  userQueryOrigin?: string;
  lastVerifiedDate: string;
  createdAt: string;
  updatedAt: string;
}

export type ReviewFeedbackType = 
  | 'helpful'
  | 'outdated'
  | 'needs-clarification'
  | 'suggestion'
  | 'general';

export type TravelerType = 
  | 'Solo Backpacker'
  | 'Family Traveler'
  | 'Guided Tour Guest'
  | 'Business Nomad'
  | 'Adventure Explorer';

export interface FAQReview {
  id: string;
  faqId: string;
  userName: string;
  userLocation?: string;
  rating: number; // 1 to 5
  feedbackType: ReviewFeedbackType;
  comment: string;
  travelerType: TravelerType;
  helpfulVotes: number;
  createdAt: string;
}

export interface UserQueryLog {
  id: string;
  query: string;
  category: FAQCategory;
  askedCount: number;
  status: 'pending' | 'answered' | 'promoted-to-faq';
  aiAnswer?: string;
  promotedFaqId?: string;
  firstAskedAt: string;
  lastAskedAt: string;
}

export interface AIInsightsStats {
  totalQueriesAnalyzed: number;
  faqsAutoGenerated: number;
  averageSatisfactionRate: number;
  emergingTopicsCount: number;
  topTrendingTopics: { topic: string; count: number; category: FAQCategory }[];
  recentSyntheses: {
    faqId: string;
    question: string;
    generatedAt: string;
    triggerQuery: string;
  }[];
}
